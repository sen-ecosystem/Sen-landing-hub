function getLang() {
  return localStorage.getItem('sentew_lang') || 'fr';
}

function setLang(lang) {
  localStorage.setItem('sentew_lang', lang);
  applyTranslations();
  // Reload pour appliquer partout
  setTimeout(() => location.reload(), 300);
}

function t(key, params) {
  let text = (translations[getLang()] || translations.fr)[key] || key;
  if (params) {
    Object.keys(params).forEach(k => {
      text = text.replace('{' + k + '}', params[k]);
    });
  }
  return text;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });
  document.documentElement.dir = getLang() === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = getLang();
}

// Sélecteur de langue flottant (à ajouter dans les pages)
function createLangSwitcher() {
  const div = document.createElement('div');
  div.style.cssText = 'position:fixed;bottom:80px;left:12px;background:white;border-radius:24px;padding:6px;display:flex;gap:2px;box-shadow:0 4px 20px rgba(0,0,0,.15);z-index:99;border:1px solid #E5E7EB;';
  ['fr','wo','en','ar'].forEach(lang => {
    const flags = {fr:'🇫🇷',wo:'🇸🇳',en:'🇬🇧',ar:'🇸🇦'};
    const btn = document.createElement('button');
    btn.textContent = flags[lang];
    btn.style.cssText = 'background:none;border:none;padding:6px 8px;border-radius:18px;cursor:pointer;font-size:14px;';
    if (getLang() === lang) btn.style.background = 'linear-gradient(135deg,#0F6B4E,#0A4D38)';
    btn.onclick = () => setLang(lang);
    div.appendChild(btn);
  });
  document.body.appendChild(div);
}

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
});
